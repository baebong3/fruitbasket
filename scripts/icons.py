def use(name: str | None, size: int = 20, cls: str = "ic") -> str:
    if not name:
        return ""
    return f'<svg class="{cls}" width="{size}" height="{size}" aria-hidden="true"><use href="#ic-{name}"/></svg>'


def item_icon(item: str, size: int = 20, cls: str = "ic") -> str:
    return use(icon_name(item), size, cls)
