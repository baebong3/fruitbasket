def icon_name(item: str) -> str | None:
    if item in _I:
        return item
    for k in _I:
        if not k.startswith("요리:") and (k in item or item in k):
            return k
    return None


def dish_icon(tags: list[str]) -> str:
    for t in tags:
        for k in ("국", "찌개", "전", "볶음", "샐러드", "음료", "김치", "저장", "디저트"):
            if k in t:
                return f"요리:{k}"
    return "요리:반찬"


